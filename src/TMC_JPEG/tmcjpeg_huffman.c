void TMCJPEGInitHuffTables(TMCJPEGContext* ctx)
{
    ctx->dcLumBits = sDCLumBits;
    ctx->dcLumVals = sDCLumVals;
    ctx->dcChrBits = sDCChrBits;
    ctx->dcChrVals = sDCChrVals;
    ctx->acLumBits = sACLumBits;
    ctx->acLumVals = sACLumVals;
    ctx->acChrBits = sACChrBits;
    ctx->acChrVals = sACChrVals;
    ctx->lumHuff.dc.count = 0;
    ctx->lumHuff.dc.codes = ctx->dcLumCodes;
    ctx->lumHuff.dc.sizes = ctx->dcLumSizes;
    ctx->lumHuff.ac.count = 0;
    ctx->lumHuff.ac.codes = ctx->acLumCodes;
    ctx->lumHuff.ac.sizes = ctx->acLumSizes;
    ctx->chrHuff.dc.count = 0;
    ctx->chrHuff.dc.codes = ctx->dcChrCodes;
    ctx->chrHuff.dc.sizes = ctx->dcChrSizes;
    ctx->chrHuff.ac.count = 0;
    ctx->chrHuff.ac.codes = ctx->acChrCodes;
    ctx->chrHuff.ac.sizes = ctx->acChrSizes;
}

void TMCJPEGBuildHuffTables(TMCJPEGContext* ctx)
{
    u32 sizes[256];
    u32 codes[256];
    int t;
    int k;
    int value;
    u16 code;
    const u8* bits;
    int len;
    int i;
    u8 size;
    const u8* vals;
    TMCJPEGHuffCodes* table;
    u8 last;

    for (t = 0; t < 4; t++) {
        switch (t) {
        case 0:
            bits = sDCLumBits;
            vals = sDCLumVals;
            table = &ctx->lumHuff.dc;
            break;
        case 1:
            bits = sDCChrBits;
            vals = sDCChrVals;
            table = &ctx->chrHuff.dc;
            break;
        case 2:
            bits = sACLumBits;
            vals = sACLumVals;
            table = &ctx->lumHuff.ac;
            break;
        case 3:
            bits = sACChrBits;
            vals = sACChrVals;
            table = &ctx->chrHuff.ac;
            break;
        }

        k = 0;
        len = 1;
        i = 1;
        for (;;) {
            if (i > bits[len]) {
                len++;
                i = 1;
                if (len > 16) {
                    sizes[k] = 0;
                    last = k;
                    break;
                }
            } else {
                sizes[k] = len + 1;
                k++;
                i++;
            }
        }

        code = 0;
        size = sizes[0];
        k = 0;
        while (1) {
            do {
                codes[k] = code;
                code++;
                k++;
            } while (size == sizes[k]);
            if (sizes[k] == 0) {
                break;
            }
            do {
                size++;
                code <<= 1;
            } while (size != sizes[k]);
        }

        k = 0;
        do {
            value = vals[k];
            table->codes[value] = codes[k];
            table->sizes[value] = sizes[k];
            k++;
        } while (k < last);
        table->count = last;
    }
}
